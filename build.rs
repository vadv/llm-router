// Embed the built web UI into the binary.
//
// The UI is a handful of files that change only with the sources, so a
// compile-time table is enough: the router ships one binary, with no static
// directory to install and no path to configure.
//
// The node build runs here so that `cargo build` alone produces a complete
// binary. Set LLM_ROUTER_SKIP_WEB_BUILD=1 to embed an existing web/dist
// instead (cross builds do this after their own node stage).

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const SKIP_ENV: &str = "LLM_ROUTER_SKIP_WEB_BUILD";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=web/src");
    println!("cargo:rerun-if-changed=web/index.html");
    println!("cargo:rerun-if-changed=web/package.json");
    println!("cargo:rerun-if-changed=web/vite.config.ts");
    // A missing or deleted dist must be noticed even though the UI build
    // writes into it below; the extra rerun after a build settles at once.
    println!("cargo:rerun-if-changed=web/dist");
    println!("cargo:rerun-if-env-changed={SKIP_ENV}");

    let web = Path::new("web");
    let dist = web.join("dist");

    if !dist.join("index.html").exists() {
        if env::var_os(SKIP_ENV).is_some() {
            panic!("web/dist/index.html is missing: build the UI in web/ first");
        }
        build_web(web);
    }

    // include_bytes! resolves relative paths against this file, which lives in
    // OUT_DIR, so every embedded file needs an absolute path.
    let dist =
        fs::canonicalize(&dist).unwrap_or_else(|error| panic!("find {}: {error}", dist.display()));

    let mut assets = Vec::new();
    collect(&dist, Path::new(""), &mut assets);
    if assets.is_empty() {
        panic!("web/dist holds no files: the UI build produced nothing");
    }
    assets.sort();

    let mut out = String::from("// Generated by build.rs from web/dist. Do not edit.\n");
    out.push_str("static ASSETS: &[(&str, &[u8], &str)] = &[\n");
    for (name, file) in &assets {
        out.push_str(&format!(
            "    ({name:?}, include_bytes!({:?}), {:?}),\n",
            file.display().to_string(),
            mime(name)
        ));
    }
    out.push_str("];\n");

    let target = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set")).join("web_assets.rs");
    fs::write(&target, out).expect("write the asset table into OUT_DIR");
}

fn build_web(web: &Path) {
    if !web.join("node_modules").exists() {
        run(web, &["npm", "ci"]);
    }
    run(web, &["npm", "run", "build"]);
}

fn run(dir: &Path, command: &[&str]) {
    let (program, args) = command.split_first().expect("a command has a program");
    let status = Command::new(program)
        .args(args)
        .current_dir(dir)
        .status()
        .unwrap_or_else(|error| {
            panic!(
                "cannot run {program} in {}: {error}\nInstall Node.js 22 or newer, \
                 or build web/dist elsewhere and set {SKIP_ENV}=1",
                dir.display()
            )
        });
    if !status.success() {
        panic!("`{}` failed in {}", command.join(" "), dir.display());
    }
}

/// Walk a directory into (request path, file on disk) pairs.
fn collect(root: &Path, relative: &Path, out: &mut Vec<(String, PathBuf)>) {
    let dir = root.join(relative);
    let entries =
        fs::read_dir(&dir).unwrap_or_else(|error| panic!("read {}: {error}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("read {}: {error}", dir.display()));
        let child = relative.join(entry.file_name());
        let kind = entry
            .file_type()
            .unwrap_or_else(|error| panic!("inspect {}: {error}", entry.path().display()));
        if kind.is_dir() {
            collect(root, &child, out);
        } else if let Some(name) = child.to_str() {
            out.push((format!("/{}", name.replace('\\', "/")), entry.path()));
        }
    }
}

/// Content type by extension. The build emits only these kinds.
fn mime(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "wasm" => "application/wasm",
        "json" => "application/json",
        "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
