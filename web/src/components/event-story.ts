import type { EventRecord } from "../api";

// Describe what the router recorded, not what the provider might be doing now.
export function eventStory(event: EventRecord) {
  const d = (
    event.detail && typeof event.detail === "object" ? event.detail : {}
  ) as Record<string, unknown>;
  const str = (key: string) =>
    typeof d[key] === "string" && d[key].trim() ? d[key] : undefined;
  const count = (key: string) =>
    typeof d[key] === "number" && Number.isSafeInteger(d[key]) && d[key] >= 0
      ? d[key]
      : undefined;
  const model = str("upstream_id");
  const target =
    [event.provider_id, model].filter(Boolean).join(" / ") || "A model";
  const pool = str("pool") ?? str("metamodel");
  let title: string, note: string;
  switch (event.kind) {
    case "ban_recorded": {
      title = `${target} was taken out of rotation`;
      const expires = count("expires_at_unix");
      note =
        [
          str("reason"),
          expires
            ? `Scheduled expiry: ${new Date(expires * 1000).toLocaleString()}`
            : undefined,
        ]
          .filter(Boolean)
          .join(" · ") || "The router recorded a temporary ban.";
      break;
    }
    case "ban_expired":
      title = `The ban on ${target} expired`;
      note =
        "That ban no longer excludes the model. This is not a health check.";
      break;
    case "model_switch":
      title = `${pool ?? "A pool"} switched models`;
      note =
        [str("from") && `From ${str("from")}`, str("to") && `to ${str("to")}`]
          .filter(Boolean)
          .join(" ") || "The router recorded a change of member.";
      break;
    case "all_models_failed": {
      title = `No member of ${pool ?? "the pool"} could serve the request`;
      const n = count("members");
      note =
        n === undefined
          ? "The request failed."
          : `The request failed with ${n} eligible ${n === 1 ? "member" : "members"}.`;
      break;
    }
    case "balance_error":
      title = `Could not refresh ${event.provider_id ?? "the provider"} balance`;
      note =
        str("error") ??
        "This check produced no new reading. It does not mean the balance is zero.";
      break;
    case "catalog_error":
      title = `Could not refresh ${event.provider_id ?? "the provider"} model catalog`;
      note = str("error") ?? "The router could not obtain a fresh model list.";
      break;
    case "catalog_refreshed":
      title = `${event.provider_id ?? "Provider"} model catalog updated`;
      note =
        count("model_count") === undefined
          ? "The refresh completed."
          : `Models reported: ${count("model_count")}.`;
      break;
    case "server_started":
      title = "Router started";
      note = str("version")
        ? `Core version ${str("version")}.`
        : "The core recorded a startup.";
      break;
    case "knowledge_card":
      title = `Model Wiki updated${model ? ` for ${model}` : ""}`;
      note = str("generator")
        ? `Card generated by ${str("generator")}.`
        : "The model card was saved.";
      break;
    case "knowledge_error":
      title = `Model Wiki update failed${model ? ` for ${model}` : ""}`;
      note = str("error") ?? "The router could not collect a new card.";
      break;
    case "retention_purged":
      title = "Old records were removed";
      note =
        ["requests", "events", "balances"]
          .filter((k) => count(k) !== undefined)
          .map((k) => `${k}: ${count(k)}`)
          .join(" · ") || "Scheduled retention cleanup ran.";
      break;
    default:
      title = `Router event: ${event.kind.replaceAll("_", " ")}`;
      note = "No description is defined for this event type.";
  }
  return { title, note, pool, model };
}

export type FeedItem = { event: EventRecord } | { cards: EventRecord[] };

/// The newest event an item stands for.
export function headOf(item: FeedItem): EventRecord {
  return "event" in item ? item.event : item.cards[0];
}

/// The feed with each run of card updates kept together. A research run
/// writes one card after another; from `from` in a row they are one item,
/// so the router's own events stay in sight.
export function foldCards(events: EventRecord[], from: number): FeedItem[] {
  const items: FeedItem[] = [];
  for (let index = 0; index < events.length; ) {
    if (events[index].kind !== "knowledge_card") {
      items.push({ event: events[index] });
      index += 1;
      continue;
    }
    let end = index;
    while (end < events.length && events[end].kind === "knowledge_card") end += 1;
    if (end - index < from) {
      for (; index < end; index++) items.push({ event: events[index] });
    } else {
      items.push({ cards: events.slice(index, end) });
      index = end;
    }
  }
  return items;
}
